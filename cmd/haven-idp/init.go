package main

import (
	"crypto/rand"
	"encoding/base64"
	"errors"
	"flag"
	"fmt"
	"io"
	"net/url"
	"os"
	"path/filepath"
	"strings"
)

// secret returns n random bytes as unpadded base64url (no characters that
// need quoting in env files, shells or YAML).
func secret(n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic("haven-idp: no randomness available: " + err.Error())
	}
	return base64.RawURLEncoding.EncodeToString(b)
}

// cmdInit writes a production-ready env file with freshly generated secrets.
// Secrets are never printed to the terminal unless --print is given.
func cmdInit(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("init", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	dir := fs.String("dir", ".", "directory for haven-idp.env")
	baseURL := fs.String("base-url", "http://localhost:8081", "public base URL clients will use (https:// in production)")
	realm := fs.String("realm", "platform", "first realm to create")
	user := fs.String("user", "admin", "first admin user")
	memory := fs.Bool("memory", false, "use the in-memory store (trying it out; data is lost on restart)")
	force := fs.Bool("force", false, "overwrite an existing file")
	toStdout := fs.Bool("print", false, "print the file to stdout instead of writing it (for a secret manager)")
	if err := fs.Parse(args); err != nil {
		return fmt.Errorf("%w\n\n%s", err, usage)
	}
	*baseURL = strings.TrimRight(strings.TrimSpace(*baseURL), "/")
	if !strings.HasPrefix(*baseURL, "http://") && !strings.HasPrefix(*baseURL, "https://") {
		return errors.New("--base-url must start with http:// or https://")
	}
	if !validRealm(*realm) {
		return fmt.Errorf("--realm %q is not a valid realm name (lowercase letters, digits, . _ -)", *realm)
	}
	if *user == "" || strings.ContainsAny(*user, " \t\n=") {
		return errors.New("--user must be a non-empty name without spaces")
	}

	content := renderEnv(*baseURL, *realm, *user, *memory)
	if *toStdout {
		_, err := io.WriteString(out, content)
		return err
	}
	path := filepath.Join(*dir, "haven-idp.env")
	flags := os.O_WRONLY | os.O_CREATE | os.O_EXCL
	if *force {
		flags = os.O_WRONLY | os.O_CREATE | os.O_TRUNC
	}
	f, err := os.OpenFile(path, flags, 0o600) // #nosec G304 -- operator-chosen directory
	if errors.Is(err, os.ErrExist) {
		return fmt.Errorf("%s already exists; refusing to overwrite its secrets (use --force to replace it)", path)
	}
	if err != nil {
		return err
	}
	if _, err := io.WriteString(f, content); err != nil {
		_ = f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Chmod(path, 0o600); err != nil { // honor 0600 even when --force replaced a looser file
		return err
	}

	_, _ = fmt.Fprintf(out, "Wrote %s (mode 0600) with a generated admin password, admin client secret and CSRF key.\n\n", path)
	_, _ = fmt.Fprintf(out, "Next:\n")
	if *memory {
		_, _ = fmt.Fprintf(out, "  haven-idp serve --env-file %s        # in-memory store: fine for trying it out\n", path)
	} else {
		_, _ = fmt.Fprintf(out, "  1. set HAVEN_IDP_DSN in %s to your PostgreSQL URL\n", path)
		_, _ = fmt.Fprintf(out, "  2. haven-idp serve --env-file %s\n", path)
	}
	_, _ = fmt.Fprintf(out, "\nYour issuer will be %s/realms/%s\n", *baseURL, *realm)
	_, _ = fmt.Fprintf(out, "Read the admin password with: grep BOOTSTRAP_PASSWORD %s\n", path)
	return nil
}

func validRealm(s string) bool {
	if s == "" || len(s) > 63 {
		return false
	}
	for i, r := range s {
		ok := r >= 'a' && r <= 'z' || r >= '0' && r <= '9'
		if i > 0 {
			ok = ok || r == '.' || r == '_' || r == '-'
		}
		if !ok {
			return false
		}
	}
	return true
}

func renderEnv(baseURL, realm, user string, memory bool) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# haven-idp configuration generated by `haven-idp init`. Keep this file private (chmod 600).\n")
	w("# Real environment variables override anything set here.\n\n")
	w("HAVEN_IDP_BASE_URL=%s\n", baseURL)
	w("HAVEN_IDP_LISTEN=%s\n\n", listenFor(baseURL))
	if memory {
		w("# In-memory store: data is lost on restart. Use HAVEN_IDP_DSN for anything real.\n")
		w("HAVEN_IDP_DEV=1\n\n")
	} else {
		w("# PostgreSQL (CloudNativePG works well). Required.\n")
		w("HAVEN_IDP_DSN=postgres://haven_idp:CHANGE_ME@localhost:5432/haven_idp?sslmode=require\n\n")
	}
	w("# Shared by every replica so the login form works behind a load balancer.\n")
	w("HAVEN_IDP_CSRF_KEY=%s\n\n", secret(32))
	w("# Encrypts what haven-idp must read back: TOTP seeds and upstream identity-provider secrets.\n")
	w("# BACK THIS UP. If it is lost those secrets cannot be decrypted (users must re-enrol TOTP).\n")
	w("# Without it TOTP and federation stay off. Rotate by listing the new key first: NEW,OLD.\n")
	w("HAVEN_IDP_SECRET_KEY=%s\n\n", secret(32))
	w("# First realm, admin user and the Admin API client (used by haven-console).\n")
	w("HAVEN_IDP_BOOTSTRAP_REALM=%s\n", realm)
	w("HAVEN_IDP_BOOTSTRAP_USER=%s\n", user)
	w("HAVEN_IDP_BOOTSTRAP_PASSWORD=%s\n", secret(18))
	w("HAVEN_IDP_ADMIN_CLIENT_SECRET=%s\n\n", secret(32))
	w("# Redirect URIs for the Haven console's own login (comma separated).\n")
	w("# HAVEN_IDP_CONSOLE_REDIRECTS=https://console.example.com/api/v1/auth/oidc/callback\n\n")
	w("# Uncomment only behind a trusted reverse proxy that sets X-Forwarded-For.\n")
	w("# HAVEN_IDP_TRUST_PROXY=1\n")
	return b.String()
}

// listenFor follows an explicit port in the base URL (a user who writes
// http://host:9000 expects the server on :9000) and otherwise uses :8081,
// which suits a TLS-terminating proxy in front.
func listenFor(baseURL string) string {
	if u, err := url.Parse(baseURL); err == nil && u.Port() != "" {
		return ":" + u.Port()
	}
	return ":8081"
}
